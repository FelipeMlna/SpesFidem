// ===== FUNCIONES DE TRADUCCIÓN =====

function getCurrentLanguage() {
    const saved = localStorage.getItem('siteLanguage');
    if (saved === 'en' || saved === 'es') return saved;
    return 'es';
}

function setLanguage(lang) {
    if (lang !== 'es' && lang !== 'en') lang = 'es';
    localStorage.setItem('siteLanguage', lang);
    document.documentElement.lang = lang;
    applyTranslations(lang);
    document.getElementById('langMenu')?.classList.remove('active');
}

function applyTranslations(lang) {
    if (lang !== 'es' && lang !== 'en') lang = 'es';
    document.documentElement.lang = lang;

    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key] !== undefined) {
            const translation = translations[lang][key];
            const icon = element.querySelector('i');
            const iconHtml = icon ? icon.outerHTML + ' ' : '';

            if (translation.includes('<br>') || translation.includes('<strong>') || translation.includes('<span>')) {
                element.innerHTML = iconHtml + translation;
            } else if (element.innerHTML.includes('<br>') && !translation.includes('<br>')) {
                const parts = translation.split(' ');
                if (parts.length > 1) {
                    element.innerHTML = iconHtml + parts[0] + ' <br>' + parts.slice(1).join(' ');
                } else {
                    element.innerHTML = iconHtml + translation;
                }
            } else {
                element.innerHTML = iconHtml + translation;
            }
        }
    });
    updateLanguageSelector(lang);
}

function updateLanguageSelector(lang) {
    const selector = document.getElementById('currentLang');
    if (selector) {
        const initials = { 'es': 'ES', 'en': 'EN' };
        const currentLang = (lang === 'en') ? 'en' : 'es';
        selector.innerHTML = `
            <span class="lang-globe">🌐</span>
            <span class="lang-name-current">${initials[currentLang]}</span>
            <i class="fas fa-chevron-down lang-arrow"></i>
        `;
    }
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations(getCurrentLanguage());
});
